// Static Vercel publication. The persistent Go server is intentionally not emulated.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),source=path.join(root,'frontend'),output=path.join(root,'dist'),marker=path.join(output,'.astralis-build');
if(path.dirname(output)!==root||path.basename(output)!=='dist')throw Error('Invalid output directory');
if(fs.existsSync(output)&&!fs.existsSync(marker))throw Error('Refusing to replace an unmanaged dist directory');
fs.rmSync(output,{recursive:true,force:true});
fs.cpSync(source,output,{recursive:true});
fs.writeFileSync(marker,'Generated by scripts/build-vercel.cjs\n');
fs.writeFileSync(path.join(output,'deployment-config.js'),'window.AstralisDeployment = Object.freeze({previewOnly:true});\n');
const htmlFile=path.join(output,'index.html');let html=fs.readFileSync(htmlFile,'utf8');
if(!html.includes('<script src="/adventure-guide.js"'))throw Error('Missing script integration marker');
html=html.replace('<script src="/adventure-guide.js"','<script src="/deployment-config.js" defer></script>\n  <script src="/adventure-guide.js"');
fs.writeFileSync(htmlFile,html);
fs.writeFileSync(path.join(output,'deployment.json'),JSON.stringify({service:'astralis-website',mode:'public-preview',persistent_backend_connected:false})+'\n');
if(fs.existsSync(path.join(output,'data'))||fs.existsSync(path.join(output,'.env')))throw Error('Private data found in deployment output');
console.log('Built Astralis website, preview and guides. Online campaigns require the persistent Go backend.');
